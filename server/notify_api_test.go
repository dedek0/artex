// TestNotifyDigestSegmentsAndDefersRemainder is end-to-end evidence of the "silent loss"
// fix. A digest message is constrained by the channel's length limit (WeCom: 4096 bytes);
// when a batch does not fit it must be split **a whole item at a time**: the items that fit
// are marked sent, the rest go back to the queue for the next message. The old implementation
// marked the entire batch successful — the truncated items were neither in the message nor in
// the failure list, while the delivery history still showed success, and the findings were
// simply gone.
//
// Four things are asserted: ① only the number actually fitted is marked sent ② the rest stay
// pending ③ deferred items **did not consume a retry attempt** ④ another round delivers the
// remainder (no deadlock).
func TestNotifyDigestSegmentsAndDefersRemainder(t *testing.T) {
	f := newNotifyFixture(t)
	hook := newFakeWebhook(t)
	// Use WeCom: its markdown limit is 4096 bytes, the tightest of the six channels.
	chID := f.createChannel(t, map[string]any{
		"name":   "Segmented digest",
		"kind":   notify.KindWeCom,
		"mode":   db.NotifyModeDigest,
		"config": map[string]any{"webhook": hook.URL},
	})
	const total = 60
	// Use long titles so that 60 findings far exceed 4096 bytes and segmentation is certain.
	longName := strings.Repeat("VeryLongFindingName", 6)
	for i := 0; i < total; i++ {
		f.record(t, longName+strconv.Itoa(i+1), "high")
	}
	ctx := context.Background()
	if _, _, err := f.pg.FanOutPendingEvents(ctx, 500); err != nil {
		t.Fatal(err)
	}
	f.agePendingBatch(t, chID)
	ch := f.channel(t, chID)

	f.n.stepDigest(ctx, ch, 50, "")
	if hook.count() != 1 {
		t.Fatalf("should send only one message, got %d", hook.count())
	}

	var sent, pending int
	if err := f.pg.QueryRow(`SELECT
    count(*) FILTER (WHERE state=$2),
    count(*) FILTER (WHERE state=$3)
  FROM notification_deliveries WHERE channel_id=$1`, chID, db.NotifyStateSent, db.NotifyStatePending).
		Scan(&sent, &pending); err != nil {
		t.Fatal(err)
	}
	if sent == 0 {
		t.Fatal("some items should be marked as sent")
	}
	if pending == 0 {
		t.Fatalf("%d findings cannot all fit in 4096 bytes; some should remain pending; sent=%d", total, sent)
	}
	if sent+pending != total {
		t.Fatalf("item counts do not add up: sent=%d pending=%d total=%d (neither sent nor pending = lost)", sent, pending, total)
	}
	// The message body must truthfully state how many items are not included here.
	if text := markdownText(t, hook.last(t)); !strings.Contains(text, "next message") {
		t.Fatalf("the message should state that some items are not included:\n%.400s", text)
	}

	// Deferred items must not consume the retry budget: claiming incremented attempts
	// optimistically, and deferring must undo it.
	var maxAttempts int
	if err := f.pg.QueryRow(`SELECT COALESCE(max(attempts),0) FROM notification_deliveries
WHERE channel_id=$1 AND state=$2`, chID, db.NotifyStatePending).Scan(&maxAttempts); err != nil {
		t.Fatal(err)
	}
	if maxAttempts > 0 {
		t.Fatalf("deferred items should not consume a retry attempt (otherwise they would fail after a few rounds), got attempts=%d", maxAttempts)
	}

	// Run repeatedly until convergence. What is asserted is **everything eventually delivered
	// and that multiple rounds really happened** — stronger than "sent in the second round":
	// it proves segmentation neither deadlocks nor drops the remainder.
	rounds := 0
	for {
		var undelivered int
		if err := f.pg.QueryRow(`SELECT count(*) FROM notification_deliveries
WHERE channel_id=$1 AND state <> $2 AND state <> $3`, chID, db.NotifyStateSent, db.NotifyStateFailed).
			Scan(&undelivered); err != nil {
			t.Fatal(err)
		}
		if undelivered == 0 {
			break
		}
		rounds++
		if rounds > total+5 {
			t.Fatalf("segmented delivery did not converge: %d rounds and %d items still outstanding", rounds, undelivered)
		}
		before := hook.count()
		f.n.stepDigest(ctx, ch, 50, "")
		if hook.count() == before {
			t.Fatalf("round %d made no progress; the remaining %d items would be stuck forever", rounds, undelivered)
		}
	}
	if rounds < 2 {
		t.Fatalf("one 4096-byte message cannot hold %d long-title findings; multiple rounds were expected, but only %d were used", total, rounds)
	}
	// Every round after the first should be pure continuation, with no channel-rejected items.
	var failed int
	if err := f.pg.QueryRow(`SELECT count(*) FROM notification_deliveries WHERE channel_id=$1 AND state=$2`,
		chID, db.NotifyStateFailed).Scan(&failed); err != nil {
		t.Fatal(err)
	}
	if failed != 0 {
		t.Fatalf("the fake receiver always returns success; there should be no failed items, got %d", failed)
	}
}

// TestNotifyBackoffTableMatchesAttemptBudget is an anti-drift assertion.
//
// The retry budget (db.MaxNotifyAttempts) and the backoff table (notifyBackoff) live in
// different packages: the former is the state machine's policy, the latter the engine's
// execution cadence. Changing only one — say raising the budget to 5 without adding a backoff
// tier — raises no error; it just makes retries 4 and 5 reuse the last interval, showing up
// as "retries mysteriously got slower", which is hard to trace back here. Asserting equal
// lengths exposes this drift in CI.
func TestNotifyBackoffTableMatchesAttemptBudget(t *testing.T) {
	if len(notifyBackoff) != db.MaxNotifyAttempts {
		t.Fatalf("backoff tier count (%d) and max attempts (%d) disagree — changing one requires changing the other",
			len(notifyBackoff), db.MaxNotifyAttempts)
	}
	// Backoff intervals must be non-decreasing, otherwise retries get more eager and worsen
	// rate limiting.
	for i := 1; i < len(notifyBackoff); i++ {
		if notifyBackoff[i] < notifyBackoff[i-1] {
			t.Fatalf("backoff intervals must be non-decreasing: tier %d %v < tier %d %v",
				i, notifyBackoff[i], i-1, notifyBackoff[i-1])
		}
	}
}

// TestNotifyRateLimitDoesNotConsumeRetryBudget pins the "take tokens first, then claim"
// order. If reversed (claim first, then discard), a delivery blocked by rate limiting would
// already have an attempt counted, and the budget would be drained by mere waiting, finally
// landing in failed.
func TestNotifyRateLimitDoesNotConsumeRetryBudget(t *testing.T) {
	// Only the token bucket is tested; no Server is needed (nor should one be built).
	n := &Notifier{buckets: map[int64]*notifyBucket{}}
	now := time.Now()
	// One per minute: a full bucket holds at most 1 token.
	if got := n.takeTokens(1, 1, notifyMaxSendsPerChannelPerTick, now); got != 1 {
		t.Fatalf("a full bucket at 1/minute should yield 1 token, got %d", got)
	}
	if got := n.takeTokens(1, 1, notifyMaxSendsPerChannelPerTick, now.Add(time.Millisecond)); got != 0 {
		t.Fatalf("an empty bucket should immediately return 0, got %d", got)
	}
	if got := n.takeTokens(1, 1, notifyMaxSendsPerChannelPerTick, now.Add(30*time.Second)); got != 0 {
		t.Fatalf("halfway through, a token should not be refilled yet, got %d", got)
	}
	if got := n.takeTokens(1, 1, notifyMaxSendsPerChannelPerTick, now.Add(time.Minute)); got != 1 {
		t.Fatalf("a full period should refill one token, got %d", got)
	}
	// An unlimited channel still uses a finite cap so a single tick cannot be held up by an
	// unbounded backlog.
	if got := n.takeTokens(2, 0, notifyUnlimitedBurstPerTick+10, now); got != notifyUnlimitedBurstPerTick {
		t.Fatalf("an unlimited channel should return the per-tick cap %d, got %d", notifyUnlimitedBurstPerTick, got)
	}
	// Token buckets are independent across channels.
	if got := n.takeTokens(1, 1, notifyMaxSendsPerChannelPerTick, now.Add(time.Millisecond)); got != 0 {
		t.Fatalf("channel 1's bucket should still be empty, got %d", got)
	}
}

// TestNotifyTakeTokensKeepsUnusedTokens pins the "take only want" semantics.
//
// The old implementation drained the whole bucket before the caller truncated it, so a
// rate=100/min channel that had accumulated a full bucket and used only 5 items this tick
// simply discarded the remaining 95 tokens; the same charge applied even when there was
// nothing pending. As a result, the documented claim of "burst up to rate_per_min items when
// there is a backlog" was never achievable.
func TestNotifyTakeTokensKeepsUnusedTokens(t *testing.T) {
	n := &Notifier{buckets: map[int64]*notifyBucket{}}
	now := time.Now()
	// The bucket starts full (100); this tick only wants 5.
	if got := n.takeTokens(1, 100, 5, now); got != 5 {
		t.Fatalf("want=5 should take exactly 5 tokens, got %d", got)
	}
	// Key assertion: the remaining 95 must still be in the bucket, not drained and discarded.
	// Time is not advanced, so anything taken can only come from the existing balance.
	if got := n.takeTokens(1, 100, 95, now); got != 95 {
		t.Fatalf("remaining tokens should still be available (expected 95), got %d — the bucket was drained", got)
	}
	if got := n.takeTokens(1, 100, 1, now); got != 0 {
		t.Fatalf("the bucket is empty and should return 0, got %d", got)
	}
	// want<=0 must not consume any token (an empty tick is free).
	n2 := &Notifier{buckets: map[int64]*notifyBucket{}}
	if got := n2.takeTokens(1, 20, 0, now); got != 0 {
		t.Fatalf("want=0 should return 0, got %d", got)
	}
	if got := n2.takeTokens(1, 20, 20, now); got != 20 {
		t.Fatalf("the want=0 call should not consume tokens; 20 should still be available, got %d", got)
	}
}

// TestDigestTickPlanDecouplesBatchSizeFromSendBudget pins the two dimensions of digest mode.
//
// Once the digest batch size is tied to the per-tick request budget, a channel with
// rate_per_min=20 can only refill 1 token per 3-second tick, so each digest message holds just
// 1 finding — functionally no better than no digest at all, while the message header still
// says "1 new finding in the last 30 minutes". This degradation raises no error and is
// invisible to the existing end-to-end cases (they pass a large limit to stepDigest manually,
// bypassing the budget calculation in step), so the decision itself is asserted here.
func TestDigestTickPlanDecouplesBatchSizeFromSendBudget(t *testing.T) {
	tokens, claimLimit := digestTickPlan()
	// One batch = one message = one request = one token. The token unit is messages, not
	// findings.
	if tokens != 1 {
		t.Fatalf("one digest batch sends one message and should consume exactly 1 token, got %d", tokens)
	}
	if claimLimit != db.MaxDigestBatchSize {
		t.Fatalf("digest batch size should be the memory bound db.MaxDigestBatchSize=%d, got %d",
			db.MaxDigestBatchSize, claimLimit)
	}
	// Key relationship: the batch size must be far larger than the per-tick request budget.
	// If they are of the same order, "how many messages to send" and "how many findings fit
	// in a batch" have been conflated into one number again.
	if claimLimit <= notifyMaxSendsPerChannelPerTick {
		t.Fatalf("digest batch size %d must not be constrained by the per-tick request budget %d — "+
			"the request budget (derived from the lease) counts requests, while batch size counts findings",
			claimLimit, notifyMaxSendsPerChannelPerTick)
	}
}

// TestNotifyTickBudgetFitsWithinLease is another anti-drift assertion.
//
// The per-channel per-tick delivery cap (notifyMaxSendsPerChannelPerTick) is derived from the
// lease duration: the worst-case serial delivery time in one tick must be < the lease,
// otherwise the lease expires before the last items are sent and, in a multi-instance
// deployment, the peer reclaims and resends them. These three constants live in different
// places; changing any one can break the relationship without any error — hence pinned here.
func TestNotifyTickBudgetFitsWithinLease(t *testing.T) {
	worst := time.Duration(notifyMaxSendsPerChannelPerTick) * notifySendTimeout
	if worst >= notifyLease {
		t.Fatalf("the worst-case time for one channel in a tick (%v) must not reach or exceed the lease (%v) "+
			"(notifyMaxSendsPerChannelPerTick=%d × notifySendTimeout=%v) — changing any of these three "+
			"constants requires checking the other two",
			worst, notifyLease, notifyMaxSendsPerChannelPerTick, notifySendTimeout)
	}
}
