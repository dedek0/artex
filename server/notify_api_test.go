// This file covers end-to-end notification behavior: finding persisted → event → fan-out →
// a real HTTP send.
//
// A security note: these cases **do not call the global Notifier.step()**; they call
// stepRealtime/stepDigest only for channels they create themselves. The reason is that step()
// iterates over every enabled channel in the database — on a development database with real
// DingTalk/WeCom bots configured, a global step would push findings generated during tests
// into those groups for real. Per-channel calls strictly limit the impact to fake receivers
// created by the tests.
//
// Cleanup: at the end of a case, delete the events it created (cascading to deliveries) and
// its channels, leaving no backlog on real channels.
//
// Assertion approach: stepRealtime/stepDigest return no values and log internally, so what is
// asserted here is **observable external behavior** (what the fake receiver received, what
// state the delivery rows ended in) rather than return values — closer to the real call path
// than stubbing return values.

// notifyFixture is the common setup for this file's cases.
type notifyFixture struct {
	s       *Server
	pg      *db.DB
	request func(method, path, body string) *httptest.ResponseRecorder
	n       *Notifier
	// A self-created task/exploration: cases record findings here, isolated from other
	// cases' data.
	taskID int64
	expID  int64
	// Events created after cleanupMark are deleted during cleanup.
	cleanupMark int64
}

func newNotifyFixture(t *testing.T) *notifyFixture {
	t.Helper()
	// All fake receivers in this file run on 127.0.0.1, while delivery denies loopback
	// addresses by default (to prevent SSRF into same-host services and cloud metadata).
	// Tests explicitly turn the switch on; the "deny by default" behavior is covered by the
	// notify package's ssrf_test.go.
	t.Setenv(notify.AllowLocalTargetsEnv, "1")
	s, _, request := trafficEvidenceServer(t)
	pg := s.m.pg

	// Create a task ourselves: the task made by the shared trafficEvidenceServer fixture does
	// not expose an exploration id, which is required to record a finding.
	task, err := s.m.CreateTask("Notification delivery test", "delivery behavior verification", nil, 0, 0)
	if err != nil {
		t.Fatal(err)
	}
	taskID, err := strconv.ParseInt(task.ID, 10, 64)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { pg.Exec(`DELETE FROM tasks WHERE id=$1`, taskID) })

	var mark int64
	if err := pg.QueryRow(`SELECT COALESCE(max(id),0) FROM notification_events`).Scan(&mark); err != nil {
		t.Fatal(err)
	}
	// Make the fixture self-contained: mark events that existed before the fixture was built
	// as already fanned out in one go.
	//
	// Why this is required: FanOutPendingEvents is **global** and expands every unfanned event
	// onto all matching channels. The shared trafficEvidenceServer fixture itself records a
	// finding (the initial one it returns), and other cases may leave residue. Without
	// isolation, these stray events would be fanned out onto this case's channel, making
	// assertions like "there should be N deliveries" flaky — and the failure would depend on
	// case execution order, which is harder to diagnose than a plain failure.
	if _, err := pg.Exec(`UPDATE notification_events SET fanned_out = true WHERE id <= $1 AND NOT fanned_out`, mark); err != nil {
		t.Fatal(err)
	}

	f := &notifyFixture{s: s, pg: pg, request: request, n: newNotifier(s), taskID: taskID, expID: task.ExpID, cleanupMark: mark}
	t.Cleanup(func() {
		if _, err := pg.Exec(`DELETE FROM notification_events WHERE id > $1`, f.cleanupMark); err != nil {
			t.Logf("failed to clean up notification events: %v", err)
		}
	})
	// The master switch must be on (other cases may have turned it off).
	if err := pg.SetBool(settingNotifyEnabled, true); err != nil {
		t.Fatal(err)
	}
	return f
}

// record persists a finding through the real evidence-writing path and returns its id.
// This path registers the notification event in the **same transaction** — the hook point
// for this feature.
func (f *notifyFixture) record(t *testing.T, vulnclass, severity string) int64 {
	t.Helper()
	out, err := f.s.evidenceStore().Record(context.Background(), db.RecordFindingInput{
		TaskID:        f.taskID,
		ExplorationID: f.expID,
		Worker:        "test",
		VulnClass:     vulnclass,
		Name:          vulnclass,
		Severity:      severity,
		Summary:       vulnclass + " summary",
		Evidence:      "poc",
	}, nil)
	if err != nil {
		t.Fatalf("failed to record the finding: %v", err)
	}
	return out.FindingID
}

